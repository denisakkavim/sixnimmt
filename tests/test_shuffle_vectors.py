@pytest.mark.parametrize(("match_seed", "hand_number"), sorted(VECTORS))
def test_shuffle_vectors_reproduce_exactly(match_seed: int, hand_number: int) -> None:
    expected_seed, expected_deck = VECTORS[(match_seed, hand_number)]

    assert hand_seed_for(match_seed, hand_number) == expected_seed
    assert shuffled_deck(match_seed, hand_number) == expected_deck


def test_different_hands_shuffle_differently() -> None:
    assert shuffled_deck(12345, 1) != shuffled_deck(12345, 2)


def test_seed_uses_1_based_hand_number() -> None:
    assert hand_seed_for(12345, 1) != hand_seed_for(12345, 0)
